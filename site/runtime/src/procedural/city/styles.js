// Rough boxes of latitude and longitude. They exist so an author who gives only a place gets a
// sensible starting look. Borders are not respected, and the answer is always marked inferred.
const REGIONS = [
  ['dutch', 50.7, 53.7, 2.5, 7.3],
  ['british', 49.8, 60.9, -11, 2],
  ['nordic', 54.5, 72, 4, 33],
  ['mediterranean', 30, 44.6, -10.5, 37],
  ['central', 44.6, 55, -5.5, 32],
  ['american', 14, 72, -170, -50],
];
/** The style whose rough region contains a place, or 'central' when none does. */
export function regionStyle(lat, lon) {
  if (!Number.isFinite(lat) || !Number.isFinite(lon)) return 'central';
  for (const [name, s, n, w, e] of REGIONS) if (lat >= s && lat <= n && lon >= w && lon <= e) return name;
  return 'central';
}
